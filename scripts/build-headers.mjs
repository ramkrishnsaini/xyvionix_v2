/**
 * Writes host configuration from one header definition:
 *   dist/_headers     Netlify and Cloudflare Pages
 *   dist/_redirects   Netlify and Cloudflare Pages
 *   vercel.json       Vercel (project root, committed)
 *
 * Runs after every build. The contact form endpoint and any analytics origin
 * are read from the environment so the policy allows exactly what is used.
 *
 *   PUBLIC_CONTACT_ENDPOINT   https URL that receives the form POST
 *   PUBLIC_ANALYTICS_ORIGIN   optional, comma-separated https origins
 */

import fs from 'node:fs';
import path from 'node:path';
import { projectRoot } from '../src/lib/content-index.mjs';
import { toHeadersFile, toVercelConfig } from './lib/security-headers.mjs';

const dist = path.join(projectRoot, 'dist');

const options = {
  formEndpoint: process.env.PUBLIC_CONTACT_ENDPOINT ?? null,
  analyticsOrigins: (process.env.PUBLIC_ANALYTICS_ORIGIN ?? '').split(',').map((s) => s.trim()).filter(Boolean),
};

// One hop only. Host-level rules (www to apex, http to https) are set at the DNS or CDN
// layer on Cloudflare; Netlify honours the domain rule below.
const redirects = [
  '# Generated by scripts/build-headers.mjs. Do not edit by hand.',
  '# Canonical host: https://xyvionix.com with no trailing slash.',
  'https://www.xyvionix.com/*  https://xyvionix.com/:splat  301!',
  'http://www.xyvionix.com/*   https://xyvionix.com/:splat  301!',
  'http://xyvionix.com/*       https://xyvionix.com/:splat  301!',
  '/index.html                 /                            301',
  '',
].join('\n');

if (fs.existsSync(dist)) {
  fs.writeFileSync(path.join(dist, '_headers'), toHeadersFile(options), 'utf8');
  fs.writeFileSync(path.join(dist, '_redirects'), redirects, 'utf8');
  console.log('Wrote dist/_headers and dist/_redirects');
} else {
  console.log('dist/ not found: skipped _headers and _redirects');
}

fs.writeFileSync(path.join(projectRoot, 'vercel.json'), `${JSON.stringify(toVercelConfig(options), null, 2)}\n`, 'utf8');
console.log('Wrote vercel.json');

if (!options.formEndpoint) {
  console.log('Note: PUBLIC_CONTACT_ENDPOINT is not set. The contact form is rendered disabled.');
}
