/**
 * One definition of the response headers, rendered for each host format.
 * The site ships no inline script or style, so the policy needs no
 * 'unsafe-inline' and no hashes.
 */

/** @param {string | null | undefined} url */
function originOf(url) {
  if (!url) return null;
  try {
    const parsed = new URL(url);
    return parsed.protocol === 'https:' ? parsed.origin : null;
  } catch {
    return null;
  }
}

/**
 * @param {{ formEndpoint?: string | null, analyticsOrigins?: string[] }} [options]
 */
export function securityHeaders(options = {}) {
  const form = originOf(options.formEndpoint);
  const analytics = (options.analyticsOrigins ?? []).map(originOf).filter(Boolean);
  const join = (...parts) => parts.flat().filter(Boolean).join(' ');

  const csp = [
    "default-src 'self'",
    join("script-src 'self'", analytics),
    "style-src 'self'",
    "img-src 'self' data:",
    "font-src 'self'",
    join("connect-src 'self'", form, analytics),
    join("form-action 'self'", form),
    "manifest-src 'self'",
    "frame-ancestors 'none'",
    "base-uri 'self'",
    "object-src 'none'",
    'upgrade-insecure-requests',
  ].join('; ');

  return {
    'Content-Security-Policy': csp,
    // Add "; preload" only after deciding to submit the domain to the preload list: it is hard to undo.
    'Strict-Transport-Security': 'max-age=63072000; includeSubDomains',
    'X-Content-Type-Options': 'nosniff',
    'Referrer-Policy': 'strict-origin-when-cross-origin',
    'Permissions-Policy': 'accelerometer=(), camera=(), geolocation=(), gyroscope=(), magnetometer=(), microphone=(), payment=(), usb=(), browsing-topics=()',
    'X-Frame-Options': 'DENY',
    'Cross-Origin-Opener-Policy': 'same-origin',
  };
}

/** Cache rules by path. Hashed assets never change; HTML is always revalidated. */
export const cacheRules = [
  { path: '/_astro/*', value: 'public, max-age=31536000, immutable' },
  { path: '/og/*', value: 'public, max-age=86400, stale-while-revalidate=604800' },
  { path: '/brand/*', value: 'public, max-age=604800' },
  { path: '/favicon.ico', value: 'public, max-age=604800' },
  { path: '/robots.txt', value: 'public, max-age=3600' },
  { path: '/llms.txt', value: 'public, max-age=3600' },
  { path: '/llms-full.txt', value: 'public, max-age=3600' },
  { path: '/rss.xml', value: 'public, max-age=3600' },
  { path: '/search-index.json', value: 'public, max-age=3600' },
  { path: '/sitemap-*.xml', value: 'public, max-age=3600' },
];

export const htmlCache = 'public, max-age=0, must-revalidate';

/** Netlify and Cloudflare Pages `_headers` format. */
export function toHeadersFile(options) {
  const headers = securityHeaders(options);
  const lines = ['# Generated by scripts/build-headers.mjs. Do not edit by hand.', '', '/*'];
  for (const [name, value] of Object.entries(headers)) lines.push(`  ${name}: ${value}`);
  lines.push(`  Cache-Control: ${htmlCache}`, '');
  for (const rule of cacheRules) lines.push(rule.path, `  Cache-Control: ${rule.value}`, '');
  lines.push('/llms.txt', '  Content-Type: text/plain; charset=utf-8', '', '/llms-full.txt', '  Content-Type: text/plain; charset=utf-8', '');
  return lines.join('\n');
}

/** Vercel `vercel.json` format. */
export function toVercelConfig(options) {
  const headers = securityHeaders(options);
  const toSource = (p) => p.replace(/\*$/, '(.*)').replace(/\*/g, '(.*)');
  return {
    $schema: 'https://openapi.vercel.sh/vercel.json',
    cleanUrls: true,
    trailingSlash: false,
    redirects: [
      { source: '/:path*', has: [{ type: 'host', value: 'www.xyvionix.com' }], destination: 'https://xyvionix.com/:path*', permanent: true },
    ],
    headers: [
      {
        source: '/(.*)',
        headers: [
          ...Object.entries(headers).map(([key, value]) => ({ key, value })),
          { key: 'Cache-Control', value: htmlCache },
        ],
      },
      ...cacheRules.map((rule) => ({ source: toSource(rule.path), headers: [{ key: 'Cache-Control', value: rule.value }] })),
    ],
  };
}
